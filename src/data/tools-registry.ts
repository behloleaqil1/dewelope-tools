/**
 * Get all tools from the registry.
 */
export function getAllTools(): ToolConfig[] {
  return toolsRegistry;
}

/**
 * Get a tool by its slug.
 */
export function getToolBySlug(slug: string): ToolConfig | undefined {
  return toolsRegistry.find((tool) => tool.slug === slug);
}

/**
 * Get all tools in a specific category.
 */
export function getToolsByCategory(categoryId: CategoryId): ToolConfig[] {
  return toolsRegistry.filter((tool) => tool.category === categoryId);
}

/**
 * Get all featured tools (for homepage display).
 */
export function getFeaturedTools(): ToolConfig[] {
  return toolsRegistry.filter((tool) => tool.featured);
}
